"""Installed package assets have explicit content-bound distribution ownership."""
import base64
from hashlib import sha256
from importlib.metadata import PackagePath, FileHash, PathDistribution
from pathlib import Path
from types import SimpleNamespace

import pytest

from api_agent.tooling.declarations import Capture
from api_agent.tooling.models import ToolSelectionError


@pytest.fixture
def package_receipt(tmp_path, monkeypatch):
    install = tmp_path / 'installed'
    package = install / 'sample_tools'
    package.mkdir(parents=True)
    source = package / 'tool.toml'
    source.write_text('version=1\n')
    item = PackagePath('sample_tools/tool.toml')
    item.size = len(source.read_bytes())
    item.hash = FileHash('sha256=' + base64.urlsafe_b64encode(sha256(source.read_bytes()).digest()).decode().rstrip('='))
    distribution = SimpleNamespace(metadata={'Name': 'sample-tools'}, files=[item],
        read_text=lambda name: 'receipt', locate_file=lambda name: install / name)
    from api_agent.tooling import declarations
    monkeypatch.setattr(declarations.metadata, 'distributions', lambda **kwargs: [distribution])
    roots = {'base': tmp_path / 'base', 'pack': tmp_path / 'pack'}
    for root in roots.values():
        root.mkdir()
    return Capture(roots), source, distribution


def test_package_resource_adds_only_receipt_owned_root(package_receipt):
    capture, source, _ = package_receipt

    path = capture.path(capture.roots['pack'] / 'instance.toml', 'package:sample-tools:sample_tools/tool.toml')
    body = capture.read(path)

    assert path == source
    assert body == b'version=1\n'
    assert capture.owner(path) == source.parent


def test_package_resource_rejects_modified_file_even_with_valid_receipt(package_receipt):
    capture, source, _ = package_receipt
    source.write_text('version=2\n')
    path = capture.path(capture.roots['pack'] / 'instance.toml', 'package:sample-tools:sample_tools/tool.toml')

    with pytest.raises(ToolSelectionError, match='differs from its ownership receipt'):
        capture.read(path)


def test_package_missing_receipt_never_uses_an_existing_checkout_file(package_receipt):
    capture, source, distribution = package_receipt
    distribution.files = []

    with pytest.raises(ToolSelectionError, match='absent from its distribution receipt'):
        capture.path(source, 'package:sample-tools:sample_tools/tool.toml')


def test_package_resource_rejects_symlink_with_unchanged_body(package_receipt):
    capture, source, _ = package_receipt
    original = source.parent / 'original.toml'
    source.rename(original)
    source.symlink_to(original)
    path = capture.path(capture.roots['pack'] / 'instance.toml', 'package:sample-tools:sample_tools/tool.toml')

    with pytest.raises(ToolSelectionError, match='Cannot capture'):
        capture.read(path)


def test_installation_bytecode_does_not_block_receipted_source_or_become_selectable(package_receipt):
    capture, source, distribution = package_receipt
    bytecode = source.parent / '__pycache__/factory.cpython-313.pyc'
    bytecode.parent.mkdir()
    bytecode.write_bytes(b'Untrusted generated bytecode')
    item = PackagePath('sample_tools/__pycache__/factory.cpython-313.pyc')
    item.size = item.hash = None
    distribution.files.append(item)
    assert capture.read(capture.package_path('package:sample-tools:sample_tools/tool.toml')) == b'version=1\n'
    with pytest.raises(ToolSelectionError, match='absent from its distribution receipt'):
        capture.package_path('package:sample-tools:sample_tools/__pycache__/factory.cpython-313.pyc')


def test_unhashed_source_remains_rejected(package_receipt):
    capture, source, distribution = package_receipt
    distribution.files[0].hash = None
    with pytest.raises(ToolSelectionError, match='content-bound file ownership'):
        capture.package_path('package:sample-tools:sample_tools/tool.toml')


@pytest.mark.parametrize('value', ['package:sample-tools', 'package::sample_tools/tool.toml',
    'package:bad/name:sample_tools/tool.toml', 'package:sample-tools:/sample_tools/tool.toml',
    'package:sample-tools:tool.toml', 'package:sample-tools:sample_tools/../tool.toml',
    'package:sample-tools:sample_tools//tool.toml', 'package:sample-tools:sample_tools\\tool.toml'])
def test_invalid_package_reference_rejects_before_metadata_lookup(package_receipt, monkeypatch, value):
    capture, _, _ = package_receipt
    from api_agent.tooling import declarations
    def unexpected_lookup(**kwargs):
        raise AssertionError('Invalid reference reached installed metadata')
    monkeypatch.setattr(declarations.metadata, 'distributions', unexpected_lookup)
    with pytest.raises(ToolSelectionError):
        capture.package_path(value)


def test_executing_source_package_is_an_explicit_owner_without_installed_fallback(tmp_path, monkeypatch):
    from api_agent.tooling import declarations
    executing = Path(declarations.__file__).absolute().parents[1]
    if executing.parent.name != 'src':
        pytest.skip('This control specifically exercises the verified checkout ownership case')
    capture = Capture({'base': executing.parent.parent, 'pack': tmp_path})
    def unexpected_lookup(**kwargs):
        raise AssertionError('Explicit source owner consulted an installed fallback')
    monkeypatch.setattr(declarations.metadata, 'distributions', unexpected_lookup)
    source = capture.package_path('package:api-agent:api_agent/tooling/declarations.py')
    assert source == Path(declarations.__file__).absolute()
    assert capture.read(source) == source.read_bytes()


@pytest.mark.parametrize('count', [0, 2])
def test_missing_or_ambiguous_distribution_owner_is_rejected(package_receipt, monkeypatch, count):
    capture, _, distribution = package_receipt
    from api_agent.tooling import declarations
    monkeypatch.setattr(declarations.metadata, 'distributions', lambda **kwargs: [distribution] * count)
    with pytest.raises(ToolSelectionError, match='one installed distribution'):
        capture.package_path('package:sample-tools:sample_tools/tool.toml')


def test_proven_duplicate_physical_metadata_alias_is_accepted(package_receipt, monkeypatch):
    capture, source, _ = package_receipt
    metadata = source.parent.parent / 'sample_tools-1.0.dist-info'
    metadata.mkdir()
    (metadata / 'METADATA').write_text('Metadata-Version: 2.1\nName: sample-tools\nVersion: 1.0\n')
    digest = base64.urlsafe_b64encode(sha256(source.read_bytes()).digest()).decode().rstrip('=')
    (metadata / 'RECORD').write_text(f'sample_tools/tool.toml,sha256={digest},{source.stat().st_size}\n'
        'sample_tools-1.0.dist-info/METADATA,,\nsample_tools-1.0.dist-info/RECORD,,\n')
    from api_agent.tooling import declarations
    monkeypatch.setattr(declarations.metadata, 'distributions',
                        lambda **kwargs: [PathDistribution(metadata), PathDistribution(metadata)])
    assert capture.read(capture.package_path('package:sample-tools:sample_tools/tool.toml')) == source.read_bytes()


@pytest.mark.parametrize('change', ['name', 'files', 'record', 'size'])
def test_distribution_requires_matching_identity_and_complete_receipt(package_receipt, change):
    capture, _, distribution = package_receipt
    if change == 'name':
        distribution.metadata = {'Name': 'unrelated-tools'}
    elif change == 'files':
        distribution.files = None
    elif change == 'record':
        distribution.read_text = lambda name: None
    else:
        distribution.files[0].size = None
    with pytest.raises(ToolSelectionError):
        capture.package_path('package:sample-tools:sample_tools/tool.toml')


@pytest.mark.parametrize('path', ['sample_tools/../escape.toml',
                                'sample_tools/escape\\file.toml'])
def test_distribution_inventory_cannot_escape_or_reinterpret_paths(package_receipt, path):
    capture, _, distribution = package_receipt
    entry = PackagePath(path)
    entry.hash = FileHash('sha256=' + 'a' * 43)
    entry.size = 1
    distribution.files.append(entry)
    with pytest.raises(ToolSelectionError):
        capture.package_path('package:sample-tools:sample_tools/tool.toml')


def test_distribution_location_cannot_escape_its_package_root(package_receipt):
    capture, source, distribution = package_receipt
    install = source.parent.parent
    distribution.locate_file = lambda name: install / ('outside.toml' if str(name).endswith('/tool.toml') else name)
    with pytest.raises(ToolSelectionError, match='escapes distribution owner'):
        capture.package_path('package:sample-tools:sample_tools/tool.toml')


def test_selected_sibling_file_must_have_its_own_receipt(package_receipt):
    capture, source, _ = package_receipt
    capture.package_path('package:sample-tools:sample_tools/tool.toml')
    sibling = source.parent / 'unowned.toml'
    sibling.write_text('version=1\n')
    with pytest.raises(ToolSelectionError, match='not distribution-owned'):
        capture.read(sibling)


def test_unsupported_file_hash_rejects_without_weakening_content_check(package_receipt):
    capture, source, distribution = package_receipt
    distribution.files[0].hash = FileHash('unsupported=abc')
    path = capture.package_path('package:sample-tools:sample_tools/tool.toml')
    with pytest.raises(ToolSelectionError, match='Unsupported package file receipt hash'):
        capture.read(path)


def test_distribution_root_directory_alias_preserves_physical_owned_source(package_receipt, tmp_path):
    capture, source, distribution = package_receipt
    alias = tmp_path / 'site-alias'
    alias.symlink_to(source.parent.parent, target_is_directory=True)
    distribution.locate_file = lambda name: alias / name
    selected = capture.package_path('package:sample-tools:sample_tools/tool.toml')
    assert selected == source
    assert capture.read(selected) == b'version=1\n'


def test_selected_package_target_cannot_disagree_with_receipt_owner(package_receipt, tmp_path):
    capture, source, distribution = package_receipt
    locate = distribution.locate_file
    distribution.locate_file = lambda name: (tmp_path / 'outside.toml'
        if type(name) is str and name == 'sample_tools/tool.toml' else locate(name))
    with pytest.raises(ToolSelectionError, match='escapes distribution owner'):
        capture.package_path('package:sample-tools:sample_tools/tool.toml')


def test_capture_keeps_package_receipt_separate_from_explicit_pack_resource(package_receipt):
    capture, source, _ = package_receipt
    selected = capture.package_path('package:sample-tools:sample_tools/tool.toml')
    assert capture.read(selected) == source.read_bytes()
    local = capture.roots['pack'] / 'local.toml'
    local.write_text('version=2\n')
    path = capture.path(source, '<resource_pack>/local.toml')
    assert path == local
    assert capture.read(path) == b'version=2\n'
    assert capture.bodies[selected] == b'version=1\n'
    capture.verify()
