"""Bounded inert declarations for reusable implementations and named instances."""
from hashlib import sha256
import base64
import hashlib
from importlib import metadata
import os
from pathlib import Path
import re
import tomllib

from api_agent.workflows.definition import _read_bounded
from .models import ToolSelectionError

MAX_CAPTURE_BYTES = 64 * 1024 * 1024
MAX_CAPTURE_FILES = 4096
_NAME = re.compile(r'[A-Z][A-Z0-9_]{0,127}\Z')
_QUALIFIED = re.compile(r'[a-z][a-z0-9_.-]{0,63}(?:/[a-z][a-z0-9_.-]{0,63})+\Z')
_INTERFACE = re.compile(r'[a-z][a-z0-9-]{0,63}@[1-9][0-9]{0,3}\Z')


class Capture:
    def __init__(self, roots, *, library_files=None):
        self.roots = dict(roots)
        self.bodies = {}
        self.library_files = library_files
        self.total = 0
        self.package_ownership = {}

    def owner(self, path):
        roots = [root for root in self.roots.values() if path.is_relative_to(root)]
        if not roots:
            raise ToolSelectionError('Tool resource escapes its declared owners')
        return max(roots, key=lambda root: len(root.parts))

    def package_path(self, value):
        parts = value.split(':', 2)
        if len(parts) != 3 or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]*', parts[1]):
            raise ToolSelectionError('Invalid distribution-owned tool resource')
        distribution_name, resource = parts[1:]
        relative = Path(resource)
        if (relative.is_absolute() or len(relative.parts) < 2 or '..' in relative.parts
                or relative.as_posix() != resource or '\\' in resource):
            raise ToolSelectionError('Package resource must be a canonical distribution path')
        # Source execution is an explicit ownership case, never an installed
        # asset fallback: only this running package under its selected base root.
        executing = Path(__file__).absolute().parents[1]
        source_root = self.roots['base'] / 'src' / 'api_agent'
        if (distribution_name == 'api-agent' and relative.parts[0] == 'api_agent'
                and executing == source_root):
            self.roots['package:' + distribution_name + ':' + relative.parts[0]] = executing
            return executing.joinpath(*relative.parts[1:])
        distributions = list(metadata.distributions(name=distribution_name))
        from api_agent.runtime.resource_pack import _distribution_identity
        from api_agent.config.source_reads import record_probe, capturing
        owners = lambda: tuple(sorted(repr(_distribution_identity(item))
            for item in metadata.distributions(name=distribution_name)))
        if capturing():
            record_probe(('tool-owners', distribution_name), owners,
                         tuple(sorted(repr(_distribution_identity(item)) for item in distributions)))
        if len(distributions) > 1:
            identities = [_distribution_identity(item) for item in distributions]
            if identities[0] is not None and all(item == identities[0] for item in identities):
                distributions = distributions[:1]
        if len(distributions) != 1:
            raise ToolSelectionError('Package resource requires one installed distribution owner')
        distribution = distributions[0]
        normalize = lambda name: re.sub(r'[-_.]+', '-', name).lower()
        name = distribution.metadata['Name']
        distribution_key = id(distribution)
        record_probe(('tool-owner-name', distribution_key),
                     lambda: distribution.metadata['Name'], name)
        if normalize(name) != normalize(distribution_name):
            raise ToolSelectionError('Package distribution identity mismatch')
        inventory = distribution.files
        receipt = distribution.read_text('RECORD') if inventory is not None else None
        record_probe(('tool-owner-receipt', distribution_key), lambda: distribution.read_text('RECORD'), receipt)
        if inventory is None or receipt is None:
            raise ToolSelectionError('Package resource requires an installed file receipt')
        located_root = Path(str(distribution.locate_file(relative.parts[0]))).absolute()
        package_root = located_root.resolve()
        ownership = {}
        for item in inventory:
            item_path = Path(str(item))
            if not item_path.parts or item_path.parts[0] != relative.parts[0]:
                continue
            if item_path.is_absolute() or '..' in item_path.parts or '\\' in str(item):
                raise ToolSelectionError('Package resource has an invalid ownership receipt')
            if item_path.suffix == '.pyc':
                # Installation-generated bytecode is never an admitted resource;
                # executable loading consumes the separately receipted source.
                continue
            if item.hash is None or item.size is None:
                raise ToolSelectionError('Package resource requires content-bound file ownership')
            physical = Path(str(distribution.locate_file(item))).absolute()
            if not physical.is_relative_to(located_root):
                raise ToolSelectionError('Package resource escapes distribution owner')
            physical = package_root / physical.relative_to(located_root)
            ownership[physical] = (item.size, item.hash.mode, item.hash.value)
        located_target = Path(str(distribution.locate_file(resource))).absolute()
        if not located_target.is_relative_to(located_root):
            raise ToolSelectionError('Package resource escapes distribution owner')
        target = package_root / located_target.relative_to(located_root)
        if target not in ownership:
            raise ToolSelectionError('Selected package asset is absent from its distribution receipt')
        self.roots['package:' + distribution_name + ':' + relative.parts[0]] = package_root
        self.package_ownership[package_root] = ownership
        return target

    def path(self, owner, value):
        if type(value) is not str or not value or len(value) > 2048 or '\\' in value or '\x00' in value:
            raise ToolSelectionError('Tool resource requires a bounded file path')
        if value.startswith('package:'):
            return self.package_path(value)
        if value.startswith('<resource_pack>/'):
            target = self.roots['pack'] / value.removeprefix('<resource_pack>/')
        else:
            target = Path(value) if Path(value).is_absolute() else owner.parent / value
        target = Path(os.path.normpath(target))
        self.owner(target)
        return target

    def add(self, path, body):
        self.owner(path)
        for root, ownership in self.package_ownership.items():
            if path.is_relative_to(root):
                expected = ownership.get(path)
                if expected is None:
                    raise ToolSelectionError('Selected package file is not distribution-owned')
                size, algorithm, digest = expected
                try:
                    actual = base64.urlsafe_b64encode(hashlib.new(algorithm, body).digest()).decode().rstrip('=')
                except ValueError:
                    raise ToolSelectionError('Unsupported package file receipt hash') from None
                if len(body) != size or actual != digest:
                    raise ToolSelectionError('Selected package file differs from its ownership receipt')
        if self.library_files is not None and path.is_relative_to(self.roots['base']):
            if path.relative_to(self.roots['base']).as_posix() not in self.library_files:
                raise ToolSelectionError('Tool resource is not owned by installed workflow distribution')
        if path in self.bodies:
            if self.bodies[path] != body:
                raise ToolSelectionError('Tool resource changed during admission')
            return body
        if len(self.bodies) >= MAX_CAPTURE_FILES or self.total + len(body) > MAX_CAPTURE_BYTES:
            raise ToolSelectionError('Tool declaration closure exceeds capture budget')
        self.bodies[path] = body
        self.total += len(body)
        return body

    def read(self, path):
        try:
            body = _read_bounded(path, self.owner(path))
        except ValueError:
            raise ToolSelectionError('Cannot capture selected tool resource') from None
        return self.add(path, body)

    def toml(self, path):
        body = self.read(path)
        try:
            return tomllib.loads(body.decode('utf-8'))
        except (UnicodeError, tomllib.TOMLDecodeError):
            raise ToolSelectionError('Invalid selected tool TOML declaration') from None

    def verify(self):
        for path in tuple(self.bodies):
            self.read(path)

    def identity(self):
        rows = []
        for path, body in self.bodies.items():
            root = self.owner(path)
            labels = sorted(key for key, value in self.roots.items() if value == root)
            rows.append((labels[0], path.relative_to(root).as_posix(), sha256(body).hexdigest()))
        return tuple(sorted(rows))


def _version(data, required, allowed, name):
    if (type(data) is not dict or not required <= set(data) or set(data) - allowed
            or type(data.get('version')) is not int or data['version'] != 1):
        raise ToolSelectionError(f'Invalid version 1 {name} declaration')


def string_map(value, name):
    if type(value) is not dict or any(type(key) is not str or type(item) is not str or not item for key, item in value.items()):
        raise ToolSelectionError(f'{name} must be a string mapping')
    return value


def instance_declaration(data):
    required = {'version', 'id', 'interface', 'implementation'}
    _version(data, required, required | {'selector', 'bindings', 'defaults', 'local',
             'services', 'prerequisites', 'infrastructure', 'expose_selector'}, 'tool instance')
    if not isinstance(data['id'], str) or not _QUALIFIED.fullmatch(data['id']):
        raise ToolSelectionError('Tool instance requires a qualified identity')
    if not isinstance(data['interface'], str) or not _INTERFACE.fullmatch(data['interface']):
        raise ToolSelectionError('Tool instance requires a versioned interface')
    if type(data['implementation']) is not str or not data['implementation']:
        raise ToolSelectionError('Tool instance requires a default implementation')
    selector = data.get('selector')
    if selector is not None and (type(selector) is not str or not _NAME.fullmatch(selector)):
        raise ToolSelectionError('Tool selector requires a configuration field name')
    if type(data.get('expose_selector', False)) is not bool:
        raise ToolSelectionError('Tool selector presentation must be boolean')
    bindings = string_map(data.get('bindings', {}), 'Tool bindings')
    if any(not _NAME.fullmatch(slot) or not _NAME.fullmatch(alias) for slot, alias in bindings.items()):
        raise ToolSelectionError('Tool bindings require configuration field names')
    defaults = data.get('defaults', {})
    if type(defaults) is not dict or set(defaults) - set(bindings):
        raise ToolSelectionError('Tool defaults require declared local bindings')
    string_map(data.get('services', {}), 'Tool service bindings')
    prerequisites = data.get('prerequisites', [])
    if type(prerequisites) is not list or len(prerequisites) > 256 or any(type(item) is not str or not item for item in prerequisites):
        raise ToolSelectionError('Tool prerequisite roots must be a bounded string array')
    local = data.get('local', {})
    if type(local) is not dict:
        raise ToolSelectionError('Local tool output binding must be a table')
    if local and (type(local) is not dict or not {'slot', 'output', 'path', 'declaration'} <= set(local) or set(local) - {'slot', 'output', 'path', 'declaration', 'activation'}
                  or any(type(local[key]) is not str or not local[key] for key in ('slot', 'output', 'path', 'declaration'))
                  or local['slot'] not in bindings or not local['path'].startswith('/')):
        raise ToolSelectionError('Invalid local tool output binding')
    if local:
        activation = local.get('activation', {})
        if (type(activation) is not dict or any(not _NAME.fullmatch(key)
                or type(item) not in (bool, int, str) for key, item in activation.items())):
            raise ToolSelectionError('Local tool activation requires typed controller values')
    infrastructure = data.get('infrastructure', {})
    if type(infrastructure) is not dict:
        raise ToolSelectionError('Tool infrastructure must be a table')
    if infrastructure and (type(infrastructure) is not dict or set(infrastructure) != {'owner', 'root', 'declarations'}
            or type(infrastructure['owner']) is not str or not infrastructure['owner']
            or type(infrastructure['root']) is not str or not infrastructure['root']
            or type(infrastructure['declarations']) is not list
            or len(infrastructure['declarations']) > 16
            or any(type(item) is not str or not item for item in infrastructure['declarations'])):
        raise ToolSelectionError('Invalid tool infrastructure ownership')
    return data


def implementation_declaration(data):
    required = {'version', 'interface', 'factory'}
    _version(data, required, required | {'inputs', 'services'}, 'tool implementation')
    if type(data['interface']) is not str or not _INTERFACE.fullmatch(data['interface']):
        raise ToolSelectionError('Tool implementation requires a versioned interface')
    if type(data['factory']) is not str:
        raise ToolSelectionError('Tool implementation requires a factory target')
    target, separator, factory = data['factory'].rpartition(':')
    if not separator or not target or factory != 'create_tool':
        raise ToolSelectionError('Tool factory must name create_tool')
    if type(data.get('inputs', {})) is not dict:
        raise ToolSelectionError('Tool implementation inputs must be a table')
    for row in data.get('inputs', {}).values():
        if type(row) is not dict:
            raise ToolSelectionError('Tool implementation input must be a table')
        if 'nonempty' in row:
            if type(row['nonempty']) is not bool or row.get('type') != 'str':
                raise ToolSelectionError('Tool nonempty policy requires a boolean on a string input')
    string_map(data.get('services', {}), 'Tool service capabilities')
    return data
